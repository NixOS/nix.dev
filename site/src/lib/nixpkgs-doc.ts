import { readFile } from "node:fs/promises";
import path from "node:path";

import { headings, toCommonmark } from "./nixpkgs-markdown";

export const docRoot = path.resolve(
  process.env.NIXPKGS_DOC_DIR ?? "./nixpkgs-doc",
);

export interface NavLeaf {
  file: string;
  label?: string;
  "id-prefix"?: string;
}

export interface NavGroup {
  label: string;
  id: string;
  children: NavNode[];
}

export interface NavCollection {
  collection: string;
  type: "nixdoc";
}

export type NavNode = NavLeaf | NavGroup | NavCollection;

export interface Nav {
  items: NavNode[];
  open: string[];
}

export async function readNav(): Promise<Nav> {
  const file = path.join(docRoot, "nav.json");
  const nav = JSON.parse(await readFile(file, "utf8"));
  if (!Array.isArray(nav?.items)) {
    throw new Error(`${file}: missing 'items'`);
  }
  const groups = (nodes: NavNode[]): void => {
    for (const node of nodes) {
      if (!("children" in node)) continue;
      if (!node.id) throw new Error(`${file}: group '${node.label}' has no id`);
      groups(node.children);
    }
  };
  groups(nav.items);
  return { items: nav.items, open: nav.open ?? [] };
}

/** A manual page from one markdown file of the nixpkgs doc tree. */
export interface DocPage {
  /** Resource path below `/nixpkgs`, from the nav position of the file. */
  slug: string;
  href: string;
  title: string;
  file: string;
  /** CommonMark text, without the title heading the page renders separately. */
  body: string;
}

/** A sidebar link to one page. */
export interface TreeLeaf {
  href: string;
  title: string;
}

/** A labelled group of sidebar entries, with the group id from nav.json. */
export interface TreeGroup {
  id: string;
  label: string;
  children: TreeNode[];
}

export type TreeNode = TreeGroup | TreeLeaf;

/**
 * Groups with too many entries to expand inline. The sidebar shows a
 * collection as one link to its first page, the index, and lists the entries
 * in a view of their own.
 */
const COLLECTIONS: Record<string, true> = {
  "chap-language-support": true,
  "chap-hooks": true,
  "chap-packages": true,
};

/** A collection with its index page split from the other entries. */
export interface Collection {
  group: TreeGroup;
  index: TreeLeaf;
  entries: TreeNode[];
  /** The groups above the collection, outermost first. */
  ancestors: TreeGroup[];
}

/** Returns the collection of `node`, or nothing for a page or a plain group. */
export function asCollection(
  node: TreeNode,
  ancestors: TreeGroup[] = [],
): Collection | undefined {
  if (!("children" in node) || !COLLECTIONS[node.id]) return undefined;
  const [index, ...entries] = node.children;
  if (!index || "children" in index) {
    throw new Error(`collection '${node.id}' does not start with a page`);
  }
  return { group: node, index, entries, ancestors };
}

/** Returns every page below `nodes`, in nav order. */
export function leaves(nodes: TreeNode[]): TreeLeaf[] {
  return nodes.flatMap((node) =>
    "children" in node ? leaves(node.children) : [node],
  );
}

/** Finds the collection that holds the page at `href`. */
export function findCollection(
  nodes: TreeNode[],
  href: string,
  ancestors: TreeGroup[] = [],
): Collection | undefined {
  for (const node of nodes) {
    if (!("children" in node)) continue;
    const collection = asCollection(node, ancestors);
    if (collection) {
      if (leaves(node.children).some((leaf) => leaf.href === href)) {
        return collection;
      }
      continue;
    }
    const found = findCollection(node.children, href, [...ancestors, node]);
    if (found) return found;
  }
  return undefined;
}

export interface DocIndex {
  pages: DocPage[];
  tree: TreeNode[];
}

/** Every nixpkgs resource path sits below this prefix. */
const BASE = "/nixpkgs";

const SUFFIXES = [".chapter.md", ".section.md", ".part.md", ".md"];

/**
 * The nav id of a markdown file, one segment of its resource path.
 *
 * FIXME: nav.json gives every group a stable id. We forgot to add the same for files, this needs to be fixed upstream.
 *
 * If nixpkgs renames the file it moves the page-id.
 */
function leafId(file: string): string {
  const name = file.split("/").pop() ?? file;
  for (const suffix of SUFFIXES) {
    if (name.endsWith(suffix)) return name.slice(0, -suffix.length);
  }
  return name;
}

/** A markdown file with its title heading as seperate field. */
interface RawPage {
  slug: string;
  href: string;
  file: string;
  title: string;
  anchor?: string;
  markdown: string;
}

async function readPage(
  file: string,
  slug: string,
): Promise<RawPage | undefined> {
  let markdown: string;
  try {
    markdown = await readFile(path.join(docRoot, file), "utf8");
  } catch {
    console.warn(
      `nixpkgs doc: skipping ${file}, not in the doc root (generated by the nixpkgs manual build?)`,
    );
    return undefined;
  }
  const href = `${BASE}/${slug}`;
  const title = headings(markdown).find((heading) => heading.depth === 1);
  if (!title) {
    return {
      slug,
      href,
      file,
      title: slug.split("/").pop() ?? slug,
      markdown,
    };
  }
  const lines = markdown.split("\n");
  const at = lines.findIndex((line) => /^# /.test(line));
  lines.splice(at, 1);
  return {
    slug,
    href,
    file,
    // The h1 title may only have code tics, otherwise the syntax would leak.
    // FIXME: Enforce this rule in nixpkgs
    title: title.title.replace(/`/g, ""),
    ...(title.id ? { anchor: title.id } : {}),
    markdown: lines.join("\n").trimStart(),
  };
}

let index: Promise<DocIndex> | undefined;

export function loadDocIndex(): Promise<DocIndex> {
  index ??= buildDocIndex();
  return index;
}

async function buildDocIndex(): Promise<DocIndex> {
  const nav = await readNav();

  const raw = new Map<string, RawPage>();
  const collectPages = async (
    nodes: NavNode[],
    prefix: string[],
  ): Promise<void> => {
    for (const node of nodes) {
      if ("children" in node) {
        await collectPages(node.children, [...prefix, node.id]);
      } else if ("file" in node) {
        const page = await readPage(
          node.file,
          [...prefix, leafId(node.file)].join("/"),
        );
        if (page) raw.set(node.file, page);
      }
    }
  };
  await collectPages(nav.items, []);

  const pages = [...raw.values()].map((page) => ({
    slug: page.slug,
    href: page.href,
    title: page.title,
    file: page.file,
    body: toCommonmark(page.markdown),
  }));

  const tree = (nodes: NavNode[]): TreeNode[] =>
    nodes.flatMap((node): TreeNode[] => {
      if ("children" in node) {
        return [
          { id: node.id, label: node.label, children: tree(node.children) },
        ];
      }
      // a nixdoc collection has no page of its own
      if (!("file" in node)) return [];
      const page = raw.get(node.file);
      if (!page) return [];
      return [{ href: page.href, title: node.label ?? page.title }];
    });

  return {
    pages,
    tree: tree(nav.items),
  };
}
